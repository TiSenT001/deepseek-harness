import { chromium } from 'file:///G:/Software/deepseek-harness/node_modules/.pnpm/playwright@1.61.1/node_modules/playwright/index.mjs'
const url = process.argv[2]
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH === undefined ? {} : { executablePath: process.env.CHROMIUM_PATH }) })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto(url, { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(3200)
await page.locator('button', { hasText: '知识库' }).first().click()
await page.waitForTimeout(700)
// search view
await page.locator('button', { hasText: '搜索' }).first().click()
await page.waitForTimeout(400)
await page.locator('.ov-search-input').fill('/TiSenT.*OS/')
await page.waitForTimeout(900)
const regexHits = await page.evaluate(() => document.querySelectorAll('.ov-search-item').length)
await page.locator('.ov-search-input').fill('tag:#work')
await page.waitForTimeout(800)
const tagHits = await page.evaluate(() => document.querySelectorAll('.ov-search-item').length)
const hasSort = await page.evaluate(() => [...document.querySelectorAll('.ov-search-bar select, .ov-search-bar .ov-graph-select')].length)
await page.screenshot({ path: '.artifacts/ui/32-search-sorted.png' })
// backlinks panel
await page.keyboard.press('Escape')
await page.waitForTimeout(300)
await page.keyboard.press('Control+o'); await page.waitForTimeout(250)
await page.keyboard.type('外部大脑'); await page.waitForTimeout(800)
await page.keyboard.press('Enter'); await page.waitForTimeout(1200)
await page.locator('.ov-tab', { hasText: '反链' }).first().click()
await page.waitForTimeout(600)
const groupsBefore = await page.evaluate(() => document.querySelectorAll('.ov-backlink-group').length)
const filter = page.locator('.ov-panel input').first()
await filter.fill('审计')
await page.waitForTimeout(500)
const groupsAfter = await page.evaluate(() => document.querySelectorAll('.ov-backlink-group').length)
await page.screenshot({ path: '.artifacts/ui/33-backlinks-filter.png' })
console.log(JSON.stringify({ regexHits, tagHits, hasSort, groupsBefore, groupsAfter }, null, 2))
await browser.close()
