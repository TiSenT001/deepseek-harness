import type { PurElement } from '../../src/pur-kernel/types.ts'

/** Scene description the kernel rebuilds into a {@link import('../../src/pur-kernel/index.ts').PurScene}. */
export interface RenderSceneInput {
  name: string
  width: number
  height: number
  view: { offsetX: number; offsetY: number; scale: number }
  backgroundColor: string
  gridColor: string
  showGrid: boolean
  imageKeys: string[]
  selectedIds: string[]
  hoveredLineId?: string
  hoverPin?: { nodeId: string; pinId: string; isOutput?: boolean; isInput?: boolean }
  selectionRect?: { x: number; y: number; w: number; h: number }
  pinDrag?: { mode: 'new' | 'relink-to' | 'relink-from'; from?: { nodeId: string; pinId: string }; to?: { nodeId: string; pinId: string }; pointerX: number; pointerY: number }
  zoomBadgeAlpha?: number
  lockPulseIds?: string[]
  editingIds?: string[]
  elements: PurElement[]
}

/** Canvas calls and decode requests the upstream run produced for each scene. */
export interface RenderTrace {
  name: string
  calls: string[]
  loads: string[]
}

